import { normalizeAnalyticsRecord } from "@/lib/analytics-tracker"
import type { AnalyticsRecord } from "@/lib/types"
import type { AnalyticsRecord as PrismaAnalyticsRecord } from "@/lib/generated/prisma/client"

/**
 * Shared analytics record data layer — maps between app types and Prisma rows.
 */

export { normalizeAnalyticsRecord } from "@/lib/analytics-tracker"

export function analyticsRecordToPrismaCreate(record: AnalyticsRecord) {
  const normalized = normalizeAnalyticsRecord(record)
  return {
    id: normalized.id,
    itemName: normalized.itemName,
    itemType: normalized.itemType,
    relatedArtist: normalized.relatedArtist,
    relatedSong: normalized.relatedSong,
    relatedCampaign: normalized.relatedCampaign,
    platform: normalized.platform,
    publishDate: normalized.publishDate,
    url: normalized.url,
    niche: normalized.niche,
    genre: normalized.genre,
    mood: normalized.mood,
    titleUsed: normalized.titleUsed,
    thumbnailText: normalized.thumbnailText,
    descriptionNotes: normalized.descriptionNotes,
    tagsUsed: normalized.tagsUsed,
    callToAction: normalized.callToAction,
    views: normalized.views,
    impressions: normalized.impressions,
    clicks: normalized.clicks,
    clickThroughRate: normalized.clickThroughRate,
    likes: normalized.likes,
    comments: normalized.comments,
    shares: normalized.shares,
    saves: normalized.saves,
    subscribersGained: normalized.subscribersGained,
    watchTimeHours: normalized.watchTimeHours,
    averageViewDuration: normalized.averageViewDuration,
    retentionNotes: normalized.retentionNotes,
    revenue: normalized.revenue,
    sales: normalized.sales,
    conversionRate: normalized.conversionRate,
    whatWorked: normalized.whatWorked,
    whatDidNotWork: normalized.whatDidNotWork,
    improvementIdeas: normalized.improvementIdeas,
    nextActions: normalized.nextActions,
    rating: normalized.rating,
    notes: normalized.notes,
    experimentId: normalized.experimentId,
    experimentName: normalized.experimentName,
    createdAt: new Date(normalized.createdAt),
    updatedAt: new Date(normalized.updatedAt),
  }
}

