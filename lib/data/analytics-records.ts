    tagsUsed: row.tagsUsed,
    callToAction: row.callToAction,
    views: row.views,
    impressions: row.impressions,
    clicks: row.clicks,
    clickThroughRate: row.clickThroughRate,
    likes: row.likes,
    comments: row.comments,
    shares: row.shares,
    saves: row.saves,
    subscribersGained: row.subscribersGained,
    watchTimeHours: row.watchTimeHours,
    averageViewDuration: row.averageViewDuration,
    retentionNotes: row.retentionNotes,
    revenue: row.revenue,
    sales: row.sales,
    conversionRate: row.conversionRate,
    whatWorked: row.whatWorked,
    whatDidNotWork: row.whatDidNotWork,
    improvementIdeas: row.improvementIdeas,
    nextActions: row.nextActions,
